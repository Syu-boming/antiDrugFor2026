/** 題目三個 cue 的畫面句（依題號自動帶入） */
export function quizLine(kind, q) {
  if (kind === 'quiz') return `題卡模式：折折說「${q.intro ?? `第 ${q.number} 題`}」，題卡 ${q.qid} 出現，旁白念題目和三個選項，之後題卡靜止（沒有倒數）。`;
  if (kind === 'reveal') return `「正解」紙印章蓋在第 ${q.answer} 項，其他選項變淡；旁白念正解。`;
  return `台口上第 ${q.number} 盞燈慢慢亮起，折折說一句話，題卡收起、回到故事。`;
}
